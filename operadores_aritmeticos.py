#Operadore aritmeticos
#Leer 2 numeros y calcular: la suma, resta, multiplicacion, division y comprobar si el primero es multiplo de segundo
number1 = int(input("Ingrese un numero: "))
number2 = int(input("Ingrese otro numero: "))

print(f"{number1} + {number2} = {number1 + number2}")
print(f"{number1} - {number2} = {number1 - number2}")
print(f"{number1} * {number2} = {number1 * number2}")
print(f"{number1} / {number2} = {number1 / number2}")
print(f"{number1} % {number2} = {number1 % number2}")
